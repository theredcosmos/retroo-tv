-- Retroo TV schema v1 — Oracle variant (19c+/23ai). Must stay structurally identical to h2/V1__create_schema.sql.
-- NUMBER(19) is what Hibernate maps java.lang.Long to on Oracle.

CREATE TABLE SONGS (
    ID            NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VIDEO_ID      VARCHAR2(11)   NOT NULL,
    TITLE         VARCHAR2(200)  NOT NULL,
    ARTIST        VARCHAR2(200)  NOT NULL,
    DECADE        VARCHAR2(10)   NOT NULL,
    RELEASE_YEAR  NUMBER(4),
    THUMBNAIL_URL VARCHAR2(500),
    CREATED_AT    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_SONGS_VIDEO_ID UNIQUE (VIDEO_ID),
    CONSTRAINT CK_SONGS_DECADE CHECK (DECADE IN ('60s', '70s', '80s', '90s', '2000s', '2010s', 'now'))
);

-- Every playback request filters by decade.
CREATE INDEX IX_SONGS_DECADE ON SONGS (DECADE);

CREATE TABLE SHARED_PLAYLISTS (
    ID            NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DISPLAY_NAME  VARCHAR2(40)   NOT NULL,
    PLAYLIST_ID   VARCHAR2(64)   NOT NULL,
    PLAYLIST_URL  VARCHAR2(300)  NOT NULL,
    PLAYLIST_NAME VARCHAR2(80)   NOT NULL,
    NOTE          VARCHAR2(140),
    CREATED_AT    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_SHARED_PLAYLIST UNIQUE (PLAYLIST_ID, DISPLAY_NAME)
);

-- The feed is always read newest-first.
CREATE INDEX IX_SHARED_PLAYLISTS_CREATED ON SHARED_PLAYLISTS (CREATED_AT DESC);
